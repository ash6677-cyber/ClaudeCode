/**
 * The themes that ship with the app.
 *
 * Constants rather than rows: they cannot be edited or deleted, they are the
 * same on every device without syncing, and "duplicate this and change it"
 * gives a writer a real starting point instead of a blank palette.
 *
 * Every preset carries its complete palette — all twenty-seven tokens, both
 * modes, fifty-four hand-tuned shades — so opening one in the theme editor
 * shows a finished colour system, not a recolour over someone else's base.
 * Inkwell alone stays empty: its fifty-four shades ARE the stylesheet's, and
 * an empty palette is what keeps it following the stylesheet when it moves.
 *
 * Every readable pair in every palette here is machine-checked to WCAG AA
 * (4.5:1) by palette-contrast.test.ts. Retune shades freely; the test is the
 * railing.
 */

